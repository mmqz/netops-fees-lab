package repo

// FeeBatchRepo persists fee import batches (migration v29, #58/#60/#61) —
// the SQLite STATE layer of the fee pipeline. The immutable snapshot and
// the Parquet analysis rows never live here. All writes run inside the
// caller's DB.Do transaction: Create (the batch's first appearance, before
// any file lands), MarkCompleted (the COMMIT POINT — the partial unique
// idempotency index fires here and only here), MarkFailed (error text in,
// retry channel open) and MarkRolledBack (terminal, audit trail kept).

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"time"

	"github.com/mmqz/netops-lab/internal/domain"
)

// FeeBatchRepo persists fee_batches rows.
type FeeBatchRepo struct{ q DBTX }

// feeBatchColumns is the canonical SELECT column list of fee_batches.
const feeBatchColumns = `id, workbook_name, sha256, sheet, fee_type, fee_year, fee_month, snapshot_path, mapping, status, rows_total, rows_imported, rows_failed, error, created_at, completed_at`

// ErrFeeIdempotentDuplicate answers a MarkCompleted that would take an
// idempotency key already held by another COMPLETED batch: the caller
// surfaces it as domain.FeeBatch.
var ErrFeeIdempotentDuplicate = errors.New("repo: 幂等键已被 completed 批次占用")

// scanFeeBatch scans one fee_batches row (the exact column order of
// feeBatchColumns) into a domain.FeeBatch.
func scanFeeBatch(s scanner) (domain.FeeBatch, error) {
	var (
		b           domain.FeeBatch
		errText     sql.NullString
		completedAt sql.NullString
		createdAt   string
	)
	err := s.Scan(&b.ID, &b.WorkbookName, &b.SHA256, &b.Sheet, &b.FeeType, &b.FeeYear, &b.FeeMonth,
		&b.SnapshotPath, &b.Mapping, &b.Status, &b.RowsTotal, &b.RowsImported, &b.RowsFailed,
		&errText, &createdAt, &completedAt)
	if err != nil {
		return domain.FeeBatch{}, err
	}
	if errText.Valid {
		b.Error = errText.String
	}
	if b.CreatedAt, err = parseTime(createdAt); err != nil {
		return domain.FeeBatch{}, err
	}
	if completedAt.Valid {
		t, err := parseTime(completedAt.String)
		if err != nil {
			return domain.FeeBatch{}, err
		}
		b.CompletedAt = &t
	}
	return b, nil
}

// Create inserts a new fee batch row. The CLI fee pipeline records the
// batch at its terminal outcome (completed or failed) — the resource
// importer's two-phase analyze/confirm does not apply; the batch id is
// generated by the service (fee_ prefix).
func (r *FeeBatchRepo) Create(ctx context.Context, b domain.FeeBatch) error {
	_, err := r.q.ExecContext(ctx, `INSERT INTO fee_batches
(id, workbook_name, sha256, sheet, fee_type, fee_year, fee_month, snapshot_path, mapping, status, rows_total, rows_imported, rows_failed, error, created_at, completed_at)
VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
		b.ID, b.WorkbookName, b.SHA256, b.Sheet, string(b.FeeType), b.FeeYear, b.FeeMonth,
		b.SnapshotPath, b.Mapping, string(b.Status), b.RowsTotal, b.RowsImported, b.RowsFailed,
		nullString(b.Error), formatTime(b.CreatedAt), nullableTimePtr(b.CompletedAt))
	if err != nil {
		return fmt.Errorf("repo: create fee batch %s: %w", b.ID, err)
	}
	return nil
}

// MarkCompleted flips a failed batch to completed with the final counts and
// the completion timestamp — the commit point of the whole import. The
// partial unique index fires here: a second completed batch with the same
// idempotency key answers ErrFeeIdempotentDuplicate.
func (r *FeeBatchRepo) MarkCompleted(ctx context.Context, id string, rowsTotal, rowsImported, rowsFailed int, completedAt time.Time) error {
	res, err := r.q.ExecContext(ctx, `UPDATE fee_batches
SET status = 'completed', rows_total = ?, rows_imported = ?, rows_failed = ?, error = NULL, completed_at = ?
WHERE id = ? AND status = 'failed'`,
		rowsTotal, rowsImported, rowsFailed, formatTime(completedAt), id)
	if err != nil {
		if isUniqueViolation(err) {
			return ErrFeeIdempotentDuplicate
		}
		return fmt.Errorf("repo: complete fee batch %s: %w", id, err)
	}
	if n, err := res.RowsAffected(); err != nil {
		return fmt.Errorf("repo: complete fee batch %s: rows affected: %w", id, err)
	} else if n == 0 {
		return fmt.Errorf("repo: complete fee batch %s: %w", id, domain.ErrNotFound)
	}
	return nil
}

// MarkFailed records the conversion failure (counts + error text). Failed
// batches keep the retry channel open: the idempotency index only covers
// completed rows.
func (r *FeeBatchRepo) MarkFailed(ctx context.Context, id string, rowsTotal, rowsFailed int, errMsg string) error {
	_, err := r.q.ExecContext(ctx, `UPDATE fee_batches
SET status = 'failed', rows_total = ?, rows_failed = ?, error = ? WHERE id = ?`,
		rowsTotal, rowsFailed, nullString(errMsg), id)
	if err != nil {
		return fmt.Errorf("repo: fail fee batch %s: %w", id, err)
	}
	return nil
}

// MarkRolledBack flips a completed batch to rolled_back (terminal audit
// state; the Parquet files were deleted by the caller's rollback, the
// snapshot stays as evidence).
func (r *FeeBatchRepo) MarkRolledBack(ctx context.Context, id string) error {
	res, err := r.q.ExecContext(ctx, `UPDATE fee_batches SET status = 'rolled_back' WHERE id = ? AND status = 'completed'`, id)
	if err != nil {
		return fmt.Errorf("repo: roll back fee batch %s: %w", id, err)
	}
	if n, err := res.RowsAffected(); err != nil {
		return fmt.Errorf("repo: roll back fee batch %s: rows affected: %w", id, err)
	} else if n == 0 {
		return fmt.Errorf("repo: roll back fee batch %s: %w", id, domain.ErrNotFound)
	}
	return nil
}

// GetByID fetches one batch, or an error wrapping domain.ErrNotFound.
func (r *FeeBatchRepo) GetByID(ctx context.Context, id string) (domain.FeeBatch, error) {
	row := r.q.QueryRowContext(ctx, `SELECT `+feeBatchColumns+` FROM fee_batches WHERE id = ?`, id)
	b, err := scanFeeBatch(row)
	if err != nil {
		return domain.FeeBatch{}, notFound("fee batch", id, err)
	}
	return b, nil
}

// CompletedByIdempotencyKey finds the completed batch holding the exact
// idempotency key (the pre-flight duplicate check; domain.ErrNotFound when
// no completed batch holds it — a failed or rolled back attempt never
// blocks). sheet is the workbook sheet of origin (#125, migration v34):
// ” matches CSV files and every pre-v34 batch.
func (r *FeeBatchRepo) CompletedByIdempotencyKey(ctx context.Context, sha256 string, feeType domain.FeeType, year, month int, mapping, sheet string) (domain.FeeBatch, error) {
	row := r.q.QueryRowContext(ctx,
		`SELECT `+feeBatchColumns+` FROM fee_batches
WHERE sha256 = ? AND sheet = ? AND fee_type = ? AND fee_year = ? AND fee_month = ? AND mapping = ? AND status = 'completed'`,
		sha256, sheet, string(feeType), year, month, mapping)
	b, err := scanFeeBatch(row)
	if err != nil {
		return domain.FeeBatch{}, notFound("completed fee batch", sha256, err)
	}
	return b, nil
}

// CompletedBySHA lists every COMPLETED batch of one file hash — any fee
// type, any sheet, any period (#125): the import-mode conflict guard asks
// "has this file been imported in the OTHER mode already?" (a first-sheet
// batch and a multi-sheet batch of the same file have different
// idempotency keys by construction, so the per-key check cannot see the
// clash — importing the same data through both modes would double-count
// it silently, the exact #125 pollution this guard refuses loudly).
func (r *FeeBatchRepo) CompletedBySHA(ctx context.Context, sha256 string) ([]domain.FeeBatch, error) {
	rows, err := r.q.QueryContext(ctx,
		`SELECT `+feeBatchColumns+` FROM fee_batches WHERE sha256 = ? AND status = 'completed'`,
		sha256)
	if err != nil {
		return nil, fmt.Errorf("repo: list completed fee batches by sha: %w", err)
	}
	defer rows.Close()
	var out []domain.FeeBatch
	for rows.Next() {
		b, err := scanFeeBatch(rows)
		if err != nil {
			return nil, fmt.Errorf("repo: scan completed fee batch: %w", err)
		}
		out = append(out, b)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("repo: list completed fee batches by sha: %w", err)
	}
	return out, nil
}

// List returns every batch (newest first) with an optional status filter
// (empty = all statuses).
func (r *FeeBatchRepo) List(ctx context.Context, status domain.FeeStatus) ([]domain.FeeBatch, error) {
	query := `SELECT ` + feeBatchColumns + ` FROM fee_batches`
	args := []any{}
	if status != "" {
		query += ` WHERE status = ?`
		args = append(args, string(status))
	}
	query += ` ORDER BY created_at DESC, id DESC`
	rows, err := r.q.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, fmt.Errorf("repo: list fee batches: %w", err)
	}
	defer rows.Close()
	var out []domain.FeeBatch
	for rows.Next() {
		b, err := scanFeeBatch(rows)
		if err != nil {
			return nil, fmt.Errorf("repo: scan fee batch: %w", err)
		}
		out = append(out, b)
	}
	return out, rows.Err()
}

// ListParquetLiveBatchIDs returns the ids of every completed batch whose
// Parquet files are authoritative (the analysis-layer GC keep-set).
func (r *FeeBatchRepo) ListParquetLiveBatchIDs(ctx context.Context) (map[string]struct{}, error) {
	rows, err := r.q.QueryContext(ctx, `SELECT id FROM fee_batches WHERE status = 'completed'`)
	if err != nil {
		return nil, fmt.Errorf("repo: list live fee batches: %w", err)
	}
	defer rows.Close()
	out := map[string]struct{}{}
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			return nil, fmt.Errorf("repo: scan live fee batch id: %w", err)
		}
		out[id] = struct{}{}
	}
	return out, rows.Err()
}
